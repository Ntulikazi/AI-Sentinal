import { useState } from 'react'
import { useQuery } from '@tanstack/react-query'
import { Download, FileJson } from 'lucide-react'
import { toast } from 'sonner'
import {
  EmptyState,
  ErrorState,
  LoadingState,
  PageHeader,
  Panel,
  SeverityBadge,
  StatusBadge,
} from '../components/ui'
import { api } from '../lib/api/client'
import { formatDate } from '../utils/format'

export function ReportsPage() {
  const [selectedId, setSelectedId] = useState('')
  const assessmentsQuery = useQuery({ queryKey: ['assessments'], queryFn: () => api.assessments() })
  const assessments = assessmentsQuery.data ?? []
  const assessmentId = selectedId || assessments[0]?.assessment_id || ''
  const reportQuery = useQuery({
    queryKey: ['reports', assessmentId],
    queryFn: () => api.report(assessmentId),
    enabled: Boolean(assessmentId),
  })

  function downloadJson() {
    if (!reportQuery.data) return
    const blob = new Blob([JSON.stringify(reportQuery.data, null, 2)], {
      type: 'application/json',
    })
    downloadBlob(blob, `assessment-${assessmentId}.json`)
  }

  async function downloadMarkdown() {
    try {
      const { blob, filename } = await api.markdownReport(assessmentId)
      downloadBlob(blob, filename)
      toast.success('Markdown report downloaded')
    } catch (error) {
      toast.error(error instanceof Error ? error.message : 'Could not download report.')
    }
  }

  return (
    <>
      <PageHeader
        eyebrow="ASSESSMENT REPORTS"
        title="Reports"
        description="Read and export reports generated by the backend. Only supported JSON and Markdown formats are available."
      />
      {assessmentsQuery.isLoading ? <LoadingState label="Loading assessments" /> :
        assessmentsQuery.isError ? <ErrorState message={assessmentsQuery.error.message} onRetry={() => void assessmentsQuery.refetch()} /> :
          assessments.length === 0 ? <EmptyState title="No reports available" description="Create an assessment first. Reports are read through assessment-scoped authorization." /> :
            <Panel title="Assessment report" description="Report content reflects persisted assessment data, coverage, findings, and limitations.">
              <div className="report-toolbar">
                <label className="field report-select"><span className="field-label">Assessment</span><select value={assessmentId} onChange={(event) => setSelectedId(event.target.value)}>{assessments.map((assessment) => <option key={assessment.assessment_id} value={assessment.assessment_id}>{assessment.assessment_id} · {assessment.status}</option>)}</select></label>
                <div className="header-actions">
                  <button className="button button-secondary" disabled={!reportQuery.data} onClick={downloadJson}><FileJson size={16} /> Download JSON</button>
                  <button className="button button-primary" disabled={reportQuery.isLoading} onClick={() => void downloadMarkdown()}><Download size={16} /> Download Markdown</button>
                </div>
              </div>
              {reportQuery.isLoading ? <LoadingState label="Loading report" /> :
                reportQuery.isError ? <ErrorState message={reportQuery.error.message} onRetry={() => void reportQuery.refetch()} /> :
                  reportQuery.data && <>
                    <div className="report-meta">
                      <div><span>Target</span><strong>{reportQuery.data.target.name}</strong></div>
                      <div><span>Mode</span><strong className="capitalize">{reportQuery.data.mode.replaceAll('_', ' ')}</strong></div>
                      <div><span>Status</span><StatusBadge status={reportQuery.data.status} /></div>
                      <div><span>Generated</span><strong>{formatDate(reportQuery.data.generated_at)}</strong></div>
                    </div>
                    <div className="metrics-grid report-metrics">
                      <ReportMetric label="Tests total" value={reportQuery.data.summary.tests_total} />
                      <ReportMetric label="Tests failed" value={reportQuery.data.summary.tests_failed} />
                      <ReportMetric label="Not tested" value={reportQuery.data.summary.tests_not_tested} />
                      <ReportMetric label="Findings" value={reportQuery.data.summary.findings_total} />
                    </div>
                    <div className="dashboard-grid">
                      <Panel title="Findings" description="Backend severity and state values.">
                        {reportQuery.data.findings.length ? <div className="compact-list">{reportQuery.data.findings.map((finding) => <div className="compact-row" key={finding.finding_id}><div><strong>{finding.title}</strong><small>{finding.affected_component}</small></div><SeverityBadge severity={finding.severity} /></div>)}</div> : <EmptyState title="No findings recorded" description="A clean report is not proof of security." />}
                      </Panel>
                      <Panel title="Coverage" description="Untested controls and reasons are preserved.">
                        {reportQuery.data.coverage.length ? <ul className="coverage-list">{reportQuery.data.coverage.map((item) => <li key={item.control}><span className={`coverage-mark ${item.tested ? 'coverage-tested' : 'coverage-untested'}`}>{item.tested ? '✓' : '—'}</span><div><strong>{item.control}</strong><small>{item.tested ? 'Tested' : item.reason ?? 'Not tested'}</small></div></li>)}</ul> : <EmptyState title="No coverage data" description="No coverage records were included in this report." />}
                      </Panel>
                    </div>
                    <Panel title="Limitations" description="Read these before interpreting results.">
                      {reportQuery.data.limitations.length ? <ul className="plain-list">{reportQuery.data.limitations.map((limitation, index) => <li key={`${index}-${limitation}`}>{limitation}</li>)}</ul> : <p className="muted">No additional limitations were recorded.</p>}
                      <p className="report-disclaimer">{reportQuery.data.disclaimer}</p>
                    </Panel>
                    <Panel title="Scanner versions">
                      {reportQuery.data.tools.length ? <ul className="version-list">{reportQuery.data.tools.map((tool) => <li key={tool.name}><span>{tool.name}</span><code>{tool.version}</code></li>)}</ul> : <p className="muted">No scanner versions were recorded.</p>}
                    </Panel>
                  </>}
            </Panel>}
    </>
  )
}

function ReportMetric({ label, value }: { label: string; value: number }) {
  return <div className="metric-card report-metric"><span className="metric-label">{label}</span><strong className="metric-value">{value}</strong></div>
}

function downloadBlob(blob: Blob, filename: string) {
  const objectUrl = URL.createObjectURL(blob)
  const link = document.createElement('a')
  link.href = objectUrl
  link.download = filename.replace(/[\\/:*?"<>|]/g, '_')
  document.body.append(link)
  link.click()
  link.remove()
  window.setTimeout(() => URL.revokeObjectURL(objectUrl), 0)
}
